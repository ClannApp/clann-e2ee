/**
 * Byte/base64/hex helpers.
 *
 * Uses `btoa`/`atob` rather than `Buffer` so the same code runs under Hermes,
 * Node and browsers. The chunking in {@link bytesToBase64} keeps
 * `String.fromCharCode` off the argument-count limit for large inputs.
 */

export function bytesToBase64(bytes: Uint8Array): string {
  let bin = '';
  const CHUNK = 0x8000;
  for (let i = 0; i < bytes.length; i += CHUNK) {
    bin += String.fromCharCode(...bytes.subarray(i, i + CHUNK));
  }
  return btoa(bin);
}

export function base64ToBytes(b64: string): Uint8Array {
  const bin = atob(b64);
  const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
  return out;
}

export function bytesToHex(bytes: Uint8Array): string {
  let out = '';
  for (const b of bytes) out += b.toString(16).padStart(2, '0');
  return out;
}

/**
 * Constant-time equality for secrets and authenticators.
 *
 * Length is not secret here (all our comparands are fixed-size keys and
 * digests), so an early length exit is fine; the byte loop must not be.
 */
export function bytesEqual(a: Uint8Array, b: Uint8Array): boolean {
  if (a.length !== b.length) return false;
  let diff = 0;
  for (let i = 0; i < a.length; i++) diff |= a[i] ^ b[i];
  return diff === 0;
}
